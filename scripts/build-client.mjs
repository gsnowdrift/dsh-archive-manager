/**
 * Build the client half: `src/client.jsx` → `lib/client.js`.
 *
 * Why a build step at all: the browser half is a single classic script that
 * registers a CJS factory (`window.__ModuleLoader__.load({id, factory})`). The
 * UI is Mantine 7 (MIT) plus React; both must arrive as that one file, and the
 * stylesheet has to be inlined because the loader serves exactly one script per
 * plugin and cannot follow a sibling `.css` request.
 *
 * React, react-dom and react/jsx-runtime stay EXTERNAL: the DSH web shell seeds
 * them (React 18.3.1) and the module loader's `require` answers them. Bundling
 * our own React copy would create a second dispatcher and break every hook.
 */
import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = resolve(root, 'lib/client.js')

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client.jsx'],
  outfile,
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'automatic',
  minify: true,
  legalComments: 'none',
  sourcemap: false,
  external: [
    'react',
    'react/jsx-runtime',
    'react-dom',
    'react-dom/client',
    '@deepseek-ai/*',
  ],
  logLevel: 'warning',
})

const js = result.outputFiles.find((file) => file.path.endsWith('.js'))
const css = result.outputFiles.find((file) => file.path.endsWith('.css'))
if (js === undefined) throw new Error('build-client: esbuild produced no JS output')
const code = js.text
const style = css === undefined ? '' : css.text

const banner = `/**
 * Archive Manager — Client half (GENERATED).
 *
 * Source: src/client.jsx · build: scripts/build-client.mjs (esbuild + Mantine 7).
 * Do not edit this file by hand; edit the source and run \`npm run build:client\`.
 */`

const output = `${banner}
window.__ModuleLoader__.load({
  id: '@gsnowdrift/dsh-archive-manager',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })
    var STYLE_ID = 'dsh-archive-manager-styles'
    if (typeof document !== 'undefined' && document.getElementById(STYLE_ID) === null) {
      var style = document.createElement('style')
      style.id = STYLE_ID
      style.textContent = ${JSON.stringify(style)}
      document.head.appendChild(style)
    }
    ;(function (module, exports, require) {
${code}
    })(module, exports, require)
    return module.exports
  },
})
`

await mkdir(dirname(outfile), { recursive: true })
await writeFile(outfile, output, 'utf8')
console.log(`build-client: wrote ${outfile} (${(output.length / 1024).toFixed(1)} KB, css ${(style.length / 1024).toFixed(1)} KB)`)
